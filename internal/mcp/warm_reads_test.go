// With a warm index, a request's freshness check walks the sources under
// the request's snapshot, and the snippets and the repository map's
// generated flags are read through that walk's resolutions
// (Walker.ReadReported). A file replaced after the walk — by a symlink to a
// file outside the root, or to an excluded file — is not read: the object
// read must be the object the walk resolved.
func TestWarmIndexReads_SwappedAfterTheWalk(t *testing.T) {
	needSymlinks(t)
	const public = "package p\n\n// Target calls Helper.\nfunc Target() string { return Helper() }\n\n// Helper is public.\nfunc Helper() string { return \"PUBLIC_SNIPPET\" }\n"
	secret := "// Code generated by a tool. DO NOT EDIT.\n\npackage p\n\n// SNIPPET_SECRET_MARKER line 5\n// SNIPPET_SECRET_MARKER line 6\n// SNIPPET_SECRET_MARKER line 7\n// SNIPPET_SECRET_MARKER line 8\n"
	for _, target := range []string{"outside", "excluded"} {
		for _, call := range []benchCall{
			{"get_context", map[string]interface{}{"path": ".", "symbol": "Target"}},
			{"search_context", map[string]interface{}{"query": "Target", "contextLimit": 3}},
			{"get_repository_map", map[string]interface{}{"path": ".", "format": "json"}},
		} {
			ws := t.TempDir()
			repo := filepath.Join(ws, "repo")
			put(t, filepath.Join(repo, "go.mod"), "module example.com/p\n\ngo 1.22\n")
			put(t, filepath.Join(repo, ".arkignore"), "secret.go\n")
			put(t, filepath.Join(repo, "p/a.go"), public)
			put(t, filepath.Join(ws, "outside/secret.go"), secret)
			put(t, filepath.Join(repo, "p/secret.go"), secret)
			put(t, filepath.Join(repo, ".arkignore"), "p/secret.go\n")
			link := filepath.Join(ws, "outside/secret.go")
			if target == "excluded" {
				link = "secret.go"
			}
			h := handlerFor(t, repo)
			if out := callOut(t, h, call.name, call.args); !strings.Contains(out, "Target") && !strings.Contains(out, `"p"`) {
				t.Fatalf("%s: cold call:\n%s", call.name, out)
			}
			// Warm: this request walks the sources itself, then the file is
			// swapped before its text is read.
			var once sync.Once
			swapped := false
			afterIndex = func() {
				once.Do(func() { replaceWithLink(t, link, filepath.Join(repo, "p/a.go")); swapped = true })
			}
			res, err := h.CallTool(call.name, call.args)
			afterIndex = nil
			if err != nil {
				t.Fatal(err)
			}
			out := res.Content[0].Text
			if !swapped {
				t.Fatalf("%s: the index was not used", call.name)
			}
			if strings.Contains(out, "SNIPPET_SECRET") || strings.Contains(out, `"isGenerated": true`) || strings.Contains(out, `"IsGenerated": true`) {
				t.Errorf("%s, link to %s: read the swapped file:\n%.800s", call.name, target, out)
			}
		}
	}
}

// The warm index's reads see the file the walk saw: an edit after the
// walk is not mixed into the answer (the read is refused as changed, or is
// of the walked object — never of other bytes at that name).
func TestWarmIndexReads_ReplacedByAnotherFile(t *testing.T) {
	repo := t.TempDir()
	put(t, filepath.Join(repo, "go.mod"), "module example.com/p\n\ngo 1.22\n")
	put(t, filepath.Join(repo, "p/a.go"), "package p\n\n// Target is public.\nfunc Target() string { return \"ORIGINAL\" }\n")
	h := handlerFor(t, repo)
	call := benchCall{"get_context", map[string]interface{}{"path": ".", "symbol": "Target"}}
	if out := callOut(t, h, call.name, call.args); !strings.Contains(out, "ORIGINAL") {
		t.Fatalf("cold call:\n%s", out)
	}
	var once sync.Once
	afterIndex = func() {
		once.Do(func() {
			// Another file (another inode) put at the name: rename over it.
			put(t, filepath.Join(repo, "p/a.go.new"), "package p\n\n// Target is public.\nfunc Target() string { return \"REPLACED_BYTES\" }\n")
			if err := os.Rename(filepath.Join(repo, "p/a.go.new"), filepath.Join(repo, "p/a.go")); err != nil {
				t.Fatal(err)
			}
		})
	}
	t.Cleanup(func() { afterIndex = nil })
	if out := callOut(t, h, call.name, call.args); strings.Contains(out, "REPLACED_BYTES") {
		t.Errorf("a snippet of bytes the walk did not see:\n%s", out)
	}
}
